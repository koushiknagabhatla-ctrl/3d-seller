export const getProduct = (id) => products.find((p) => p.id === id)

export const formatPrice = (n) =>
  new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(n)

export const modelSrc = (p) => {
  if (!p?.modelUrl) return null
  if (/^https?:\/\//.test(p.modelUrl)) return p.modelUrl
  const base = import.meta.env.VITE_MODELS_BASE_URL
  return base ? `${base.replace(/\/$/, '')}/${p.modelUrl}` : null
}
